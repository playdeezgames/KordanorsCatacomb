#!/usr/bin/env python3
"""Turns the original glyph-JSON fonts (assets/fonts/CyFont*.json) into odin/game/font_data.odin.

Each font is fixed width, ASCII 32..127. Each glyph row is a u8 bit mask, bit x = pixel in column x.
"""
import json, os

root = os.path.join(os.path.dirname(__file__), "..")
src = os.path.join(root, "assets", "fonts")
FONTS = [("Font3x5", "CyFont3x5.json"), ("Font4x6", "CyFont4x6.json"), ("Font5x7", "CyFont5x7.json"), ("Font8x8", "CyFont8x8.json")]


def load(name):
    with open(os.path.join(src, name), encoding="utf-8-sig") as f:
        return json.load(f)


lines = ["// Generated by tools/gen_fonts.py from the original CyFont*.json files. Do not edit.", "package game", ""]
lines.append("FONT_FIRST :: 32\nFONT_COUNT :: 96\nFONT_MAX_HEIGHT :: 8\n")
lines.append("Font_Data :: struct {\n\twidth:  int,\n\theight: int,\n\tglyphs: [FONT_COUNT][FONT_MAX_HEIGHT]u8,\n}\n")
lines.append("FONTS := [Font]Font_Data {")
for name, path in FONTS:
    font = load(path)
    widths = {g["Width"] for g in font["Glyphs"].values()}
    assert len(widths) == 1, (path, widths)
    width = widths.pop()
    assert width <= 8 and font["Height"] <= 8
    lines.append(f"\t.{name} = {{\n\t\twidth = {width},\n\t\theight = {font['Height']},\n\t\tglyphs = {{")
    for c in range(32, 128):
        g = font["Glyphs"].get(chr(c))
        rows = [0] * 8
        if g:
            for y, cols in g["Lines"].items():
                for x in cols:
                    rows[int(y)] |= 1 << x
        lines.append("\t\t\t{" + ", ".join(str(v) for v in rows) + "},")
    lines.append("\t\t},\n\t},")
lines.append("}")
out = os.path.join(root, "odin", "game", "font_data.odin")
with open(out, "w") as f:
    f.write("\n".join(lines) + "\n")
print("wrote", out)
